// the one glyph the object form cannot carry, since a backslash key would
// have to be escaped and then no longer reads as the character it draws
F[String.fromCharCode(92)] = '...../#..../.#.../..#../...#./....#/.....';

const W = 5, H = 7;
// A character with no glyph draws as a hollow box rather than as nothing: a
// caption with a visible hole in it is a bug report, one with a word silently
// shortened is not.
const MISSING = '#####/#...#/#...#/#...#/#...#/#####/.....';

const bits = (spec) => spec.split('/').map((row) => {
  let m = 0;
  for (let i = 0; i < W; i++) if (row[i] === '#') m |= 1 << (W - 1 - i);
  return m;
});
const rows = {};
for (const ch in F) rows[ch] = bits(F[ch]);
const missing = bits(MISSING);

const opt = (o) => ({
  scale: Math.max(1, Math.round((o && o.scale) || 2)),
  rgb: (o && o.rgb) || [20, 20, 20],
  alpha: o && o.alpha !== undefined ? o.alpha : 1,
  track: o && o.track !== undefined ? o.track : 1,
});

/** alpha-composited fill, clipped to the buffer */
function box(buf, w, h, x, y, bw, bh, rgb, alpha) {
  if (!(alpha > 0)) return;
  const k = alpha > 1 ? 1 : alpha;
  const x0 = Math.max(0, Math.round(x)), x1 = Math.min(w, Math.round(x) + Math.round(bw));
  const y0 = Math.max(0, Math.round(y)), y1 = Math.min(h, Math.round(y) + Math.round(bh));
  for (let j = y0; j < y1; j++) {
    for (let i = x0; i < x1; i++) {
      const o = (j * w + i) * 4;
      buf[o] += (rgb[0] - buf[o]) * k;
      buf[o + 1] += (rgb[1] - buf[o + 1]) * k;
      buf[o + 2] += (rgb[2] - buf[o + 2]) * k;
    }
  }
}

function measure(str, o) {
  const p = opt(o);
  if (!str.length) return 0;
  return str.length * (W + p.track) * p.scale - p.track * p.scale;
}

function text(buf, w, h, x, y, str, o) {
  const p = opt(o);
  const adv = (W + p.track) * p.scale;
  const ox = Math.round(x), oy = Math.round(y);
  for (let n = 0; n < str.length; n++) {
    const g = rows[str[n]] || missing;
    const gx = ox + n * adv;
    // whole glyphs off either end cost nothing; a partly visible one still
    // clips per pixel inside box()
    if (gx + W * p.scale <= 0 || gx >= w) continue;
    for (let r = 0; r < H; r++) {
      const m = g[r];
      if (!m) continue;
      for (let c = 0; c < W; c++) {
        if (!(m & (1 << (W - 1 - c)))) continue;
        box(buf, w, h, gx + c * p.scale, oy + r * p.scale, p.scale, p.scale, p.rgb, p.alpha);
      }
    }
  }
  return measure(str, o);
}

module.exports = { text, measure, box, W, H };
